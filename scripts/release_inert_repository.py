def _earlier_versions_unchanged(before: Snapshot, after: Snapshot) -> list[str]:
    """(a) Every version 1..N projects exactly what it projected before the edit."""
    failures = []
    for number in range(1, before.current_version + 1):
        old, new = before.policies.get(number), after.policies.get(number)
        if old is None or new is None or canonical_digest(old) != canonical_digest(new):
            failures.append(f"(a) version {number} no longer projects what it did")
    return failures


def _new_version_adds_only(
    before: Snapshot, after: Snapshot, repository: str, decided: str
) -> list[str]:
    """(b) Version N+1 is version N, its prose, and exactly one more inert repository."""
    n = before.current_version
    released, previous = after.policies.get(n + 1), before.policies[n]
    if released is None:
        return [f"(b) version {n + 1} is not registered"]
    failures = []
    expected = sorted({*previous["inert_landing"]["repositories"], repository})
    if released.get("decided") != decided:
        failures.append(f"(b) version {n + 1} is not decided {decided}")
    if (released.get("inert_landing") or {}).get("repositories") != expected:
        failures.append(f"(b) version {n + 1}'s inert population is not version {n}'s plus one")
    if without_release_fields(released) != without_release_fields(previous):
        failures.append(f"(b) version {n + 1} changes more than the inert population")
    return failures


def _contract_is_new_version(before: Snapshot, after: Snapshot) -> list[str]:
    """(c) The regenerated contract is exactly what the new version renders, and names N+1."""
    n = before.current_version
    try:
        committed = CONTRACT.read_text(encoding="utf-8")
        contract_version = json.loads(committed).get("policy_version")
    except (OSError, ValueError, AttributeError) as error:
        return [f"(c) {CONTRACT.relative_to(ROOT)} does not parse: {error}"]
    failures = []
    if contract_version != n + 1:
        failures.append(f"(c) the contract names version {contract_version}, not {n + 1}")
    if committed != after.contract:
        failures.append("(c) the contract is not what current() renders")
    return failures


def _new_version_in_force(before: Snapshot, after: Snapshot) -> list[str]:
    """(d) CURRENT_VERSION and current() are version N+1, and the registry gained exactly it."""
    n, failures = before.current_version, []
    if after.current_version != n + 1 or after.current_is != n + 1:
        failures.append(
            f"(d) CURRENT_VERSION is {after.current_version} and current() is version "
            f"{after.current_is}; both must be {n + 1}"
        )
    if after.registry != [*before.registry, n + 1]:
        failures.append(f"(d) the registry is {after.registry}, not {before.registry} + {n + 1}")
    return failures


def _modules_pass_the_linters() -> list[str]:
    """(e) The edited modules pass the repository's own `ruff check` and `ruff format --check`, so
    exit 0 never hands a caller a release its quality gate refuses."""
    ruff = Path(sys.executable).parent / "ruff"
    if not ruff.exists():
        return [f"(e) ruff is not installed beside {sys.executable}; run through `uv run`"]
    failures = []
    for args in (["check", "--quiet"], ["format", "--check", "--quiet"]):
        done = subprocess.run(
            [str(ruff), *args, str(POLICY), str(HISTORY)], cwd=ROOT, capture_output=True, text=True
        )
        if done.returncode != 0:
            failures.append(f"(e) ruff {args[0]}: {(done.stdout + done.stderr).strip()[:400]}")
    return failures


def self_check(before: Snapshot, after: Snapshot, repository: str, decided: str) -> list[str]:
    """Every reason the edited tree is not version N plus `repository`. Empty means it is."""
    return [
        *_earlier_versions_unchanged(before, after),
        *_new_version_adds_only(before, after, repository, decided),
        *_contract_is_new_version(before, after),
        *_new_version_in_force(before, after),
        *_modules_pass_the_linters(),
    ]


# ---------------------------------------------------------------------------
# Generation: text transforms over the two modules, in the shape of the hand-made releases.
# ---------------------------------------------------------------------------


def _one(pattern: str, text: str, what: str, flags: int = 0) -> re.Match[str]:
    found = list(re.finditer(pattern, text, flags))
    if len(found) != 1:
        raise Refusal(f"expected exactly one {what}, found {len(found)}")
    return found[0]


def _replace_once(text: str, old: str, new: str, what: str) -> str:
    if text.count(old) != 1:
        raise Refusal(f"expected exactly one {what}, found {text.count(old)}")
    return text.replace(old, new)


def _literal_lines(text: str, indent: int) -> str:
    """`text` as implicitly concatenated string literals, each line within the line length."""
    width = LINE_LENGTH - indent - 2  # the two quotes
    words, pieces, line = text.split(" "), [], ""
    for word in words:
        candidate = f"{line} {word}" if line else word
        if len(candidate) + 1 <= width:  # + 1 for the trailing space every piece but the last has
            line = candidate
            continue
        if len(word) + 1 > width:
            raise Refusal(f"{word[:40]}... is too long to fit one line of the policy module")
        if line:
            pieces.append(line)
        line = word
    pieces.append(line)
    pad = " " * indent
    rendered = [f'{pad}"{piece} "' for piece in pieces[:-1]] + [f'{pad}"{pieces[-1]}"']
    return "\n".join(rendered) + "\n"


def _comment_lines(text: str, indent: int) -> str:
    prefix = " " * indent + "# "
    wrapped = textwrap.wrap(
        text, LINE_LENGTH - len(prefix), break_long_words=True, break_on_hyphens=False
    )
    return "".join(f"{prefix}{line}\n" for line in wrapped)


def _sentence(reason: str) -> str:
    return reason if reason.endswith((".", "!", "?")) else reason + "."


def _inert_rationale(n: int, count: int, repository: str, reason: str, decided: str) -> str:
    return (
        f"The rule ADR-0038 declared, over the {count} repositories version {n} named and one "
        f"more, with the same authors. "
        f"WHAT IS ADDED. {repository}, by version {n + 1}, {decided}: {_sentence(reason)} "
        f"Devon decided on 2026-10-24 that each fork joining the orchestrator's fork-sync lane is "
        f"an explicit, versioned grant in this policy; this version was generated by "
        f"`scripts/release_inert_repository.py`, which adds one repository and refuses the release "
        f"unless every other term projects unchanged. "
        f"NOTHING ELSE IS WIDENED. The authors, the excluded ecosystems, the freshness condition "
        f"and the exempted authors are version {n}'s. "
        f"The deploying population and every term keyed off it are version {n}'s objects, "
        f"unchanged. The two populations remain disjoint."
    )


def _policy_rationale(n: int, repository: str, reason: str) -> str:
    return (
        f"Version {n}'s populations and terms, with one repository added to the inert lane: "
        f"{repository}. Nothing else is widened: the same deploying repositories, the same change "
        f"classes, the same risks, the same criteria, the same remedies, the same rollout pins, "
        f"the same conditions on the act, and the same inert authors and terms. "
        f"WHY IT EXISTS. {_sentence(reason)}"
    )


_RATIONALE_BLOCK = r"    rationale=\(\n(?:        .*\n)+?    \),\n"


def _release_policy_module(
    source: str,
    n: int,
    repository: str,
    reason: str,
    decided: str,
    inert_count: int,
    same_landing_since: int,
) -> tuple[str, str]:
    """(the new deploy_policy.py, version N's verbatim block for the history module)."""
    header = _one(
        rf"^# (-+)\n# Version {n} -- the version in force\.\n# -+\n\n",
        source,
        f"version {n} section header",
        re.M,
    )
    rule = header.group(1)
    current_line = f"CURRENT_VERSION: Final = {n}\n"
    end = source.find(current_line, header.end())
    if end < 0 or source.count(current_line) != 1:
        raise Refusal(f"expected exactly one `{current_line.strip()}`")
    block = source[header.end() : end]
    parts = _one(
        rf"\A(?P<comment>(?:#.*\n)*)"
        rf"(?P<inert>_V{n}_INERT: Final = InertLanding\(\n.*?\n\)\n)\n\n"
        rf"(?P<policy>V{n}: Final = DeployPolicy\(\n.*?\n\)\n)\n\n\Z",
        block,
        f"version {n} definitions",
        re.S,
    )
    old_decided = _one(r'    decided="(\d{4}-\d{2}-\d{2})",\n', parts["policy"], "decided date")
    moved = (
        f"# {rule}\n# Version {n} -- Devon, {old_decided.group(1)}.\n# {rule}\n\n"
        f"{parts['comment']}{parts['inert']}\n\n{parts['policy']}\n\n"
    )

    # The new inert population: version N's, every entry and comment verbatim, plus one.
    inert = parts["inert"].replace(f"_V{n}_INERT: Final", f"_V{n + 1}_INERT: Final", 1)
    closing = "        }\n    ),\n    permitted_authors="
    inert = _replace_once(
        inert,
        closing,
        _comment_lines(f"Added by version {n + 1}, {decided}. {_sentence(reason)}", 12)
        + f'            "{repository}",\n'
        + closing,
        "close of the inert repositories",
    )
    _one(_RATIONALE_BLOCK, inert, "inert rationale")
    inert = re.sub(
        _RATIONALE_BLOCK,
        lambda _: (
            "    rationale=(\n"
            + _literal_lines(_inert_rationale(n, inert_count, repository, reason, decided), 8)
            + "    ),\n"
        ),
        inert,
        count=1,
    )

    policy = parts["policy"].replace(f"V{n}: Final", f"V{n + 1}: Final", 1)
    policy = _replace_once(policy, f"    version={n},\n", f"    version={n + 1},\n", "version")
    policy = policy.replace(old_decided.group(0), f'    decided="{decided}",\n', 1)
    _one(_RATIONALE_BLOCK, policy, "policy rationale")
    policy = re.sub(
        _RATIONALE_BLOCK,
        lambda _: (
            "    rationale=(\n"
            + _literal_lines(_policy_rationale(n, repository, reason), 8)
            + "    ),\n"
        ),
        policy,
        count=1,
    )
    landing = _one(
        r"(?:    #.*\n)*    landing=(_V\d+_LANDING),\n", policy, "deploying-lane landing term"
    )
    declared = f"versions {same_landing_since} to {n}" if same_landing_since < n else f"version {n}"
    policy = policy.replace(
        landing[0],
        _comment_lines(
            f"The SAME OBJECT {declared} declared: this version makes no statement about the "
            "deploying lane.",
            4,
        )
        + f"    landing={landing[1]},\n",
        1,
    )
    policy = _replace_once(
        policy,
        f"    inert_landing=_V{n}_INERT,\n",
        f"    inert_landing=_V{n + 1}_INERT,\n",
        "inert_landing reference",
    )

    comment = (
        f"VERSION {n}'S INERT POPULATION AND TERMS, with one more repository. The same authors, "
        f"the same exclusions, the same freshness condition and the same exempted authors."
    )
    released = (
        f"# {rule}\n# Version {n + 1} -- the version in force.\n# {rule}\n\n"
        + _comment_lines(comment, 0)
        + f"{inert}\n\n{policy}\n\n"
    )
    out = (
        source[: header.start()]
        + released
        + f"CURRENT_VERSION: Final = {n + 1}\n"
        + source[end + len(current_line) :]
    )
    out = _replace_once(
        out,
        f"def current() -> DeployPolicy:\n    return V{n}\n",
        f"def current() -> DeployPolicy:\n    return V{n + 1}\n",
        "current()",
    )
    return out, moved


_TERM = re.compile(r"\b_V\d+_[A-Z0-9_]+\b")
_IMPORTS = re.compile(r"^from app\.deploy_policy import \(\n(?P<names>(?:    \w+,\n)+)\)\n", re.M)


def _terms_to_import(source: str, moved: str) -> list[str]:
    """The terms version N's block names and neither defines nor finds imported.

    A version that introduced terms of its own (version 14's `_V14_LANDING`, for one) keeps them
    in the policy module, because the next version still carries them; when it moves here, the
    history module must import them or the move does not load.
    """
    imports = _one(_IMPORTS.pattern, source, "import from app.deploy_policy", re.M)
    imported = set(re.findall(r"\w+", imports["names"]))
    defined = set(re.findall(r"^(_V\d+_[A-Z0-9_]+): Final", moved, re.M))
    return sorted(set(_TERM.findall(moved)) - defined - imported)


def _release_history_module(source: str, n: int, moved: str) -> str:
    out = _replace_once(
        source,
        f"    V{n},\n    DeployPolicy,\n",
        f"    V{n + 1},\n    DeployPolicy,\n",
        f"import of V{n}",
    )
    # Appended to the import list here and put in order by `_sort_history_imports` once written:
    # the order is ruff's to decide, and the self-check holds the result to ruff.
    added = "".join(f"    {name},\n" for name in _terms_to_import(out, moved))
    if added:
        closing = "    WorkflowPin,\n)\n"
        out = _replace_once(out, closing, f"{closing[:-2]}{added})\n", "close of the imports")
    anchor = "# Every version ever, retained."
    out = _replace_once(out, anchor, moved + anchor, "registry comment")
    return _replace_once(
        out, f"        V{n},\n    )\n}}", f"        V{n},\n        V{n + 1},\n    )\n}}", "registry"
    )


def _inject(
    fault: str, n: int, repository: str, decided: str, policy: str, history: str
) -> tuple[str, str]:
    if fault not in _SOURCE_FAULTS:
        return policy, history
    module, old, new = _SOURCE_FAULTS[fault]
    fill = {"<repository>": repository, "<decided>": decided, "<new>": str(n + 1), "<old>": str(n)}
    for placeholder, value in fill.items():
        old, new = old.replace(placeholder, value), new.replace(placeholder, value)
    if module == "policy":
        return _replace_once(policy, old, new, f"fault {fault}"), history
    return policy, _replace_once(history, old, new, f"fault {fault}")


