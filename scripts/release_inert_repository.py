"""Release the next deploy-policy version: the current one plus one repository in the inert lane.

    uv run python scripts/release_inert_repository.py --repository <owner/name> --reason "<text>"

Devon decided on 2026-10-24 that each fork joining the orchestrator's fork-sync lane stays an
explicit, versioned grant in this policy, and that the onboarding tool generates that release
rather than a person hand-writing it. This is the generator. It edits the working tree only -- no
git -- the way the hand-made version 12 release did (3bd6472):

- version N's definitions move unedited into `app/deploy_policy_history.py`, which imports the new
  version instead of the old one and registers both in `REGISTRY`;
- `app/deploy_policy.py` gains `_V<N+1>_INERT` and `V<N+1>`, whose inert population is version N's
  plus the repository, and `CURRENT_VERSION = N+1`;
- `contracts/ratified_rollout_policy.json` is regenerated by
  `scripts.write_ratified_rollout_policy`.

No test is written: `tests/test_deploy_policy.py` asserts every inert-only release generically.

THE SELF-CHECK IS THE SAFETY PROPERTY, not the text editing. After writing, a fresh interpreter
imports the edited modules, and the release is refused -- every touched file restored to its
original bytes -- unless (a) every version 1..N projects byte-identical `policy_dict` output,
(b) version N+1 projects version N's output except its prose and an inert population of exactly
version N's plus the repository, (c) the regenerated contract parses and names version N+1, and
(d) `CURRENT_VERSION` and `current()` are version N+1.

Exit codes: 0 released, and stdout is exactly `<N+1> <repository>`; 2 the repository is already in
the current version's inert population, and nothing is touched; 1 anything else, with every file
restored. Diagnostics go to stderr.

THIS SCRIPT NEVER IMPORTS `app`. The virtualenv installs this repository editable, so an in-process
import resolves wherever that install points rather than to the tree beside this file. Every read
of the policy runs in a subprocess whose working directory is this tree, and refuses if `app`
resolved anywhere else.
"""

from __future__ import annotations

import argparse
import hashlib
import json
import os
import re
import subprocess
import sys
import tempfile
import textwrap
from dataclasses import dataclass
from datetime import date
from pathlib import Path
from typing import NoReturn

ROOT = Path(__file__).resolve().parent.parent
POLICY = ROOT / "app" / "deploy_policy.py"
HISTORY = ROOT / "app" / "deploy_policy_history.py"
CONTRACT = ROOT / "contracts" / "ratified_rollout_policy.json"
TOUCHED = (POLICY, HISTORY, CONTRACT)

REPOSITORY_NAME = re.compile(r"^[a-z0-9-]+/[a-z0-9._-]+$")
LINE_LENGTH = 100  # pyproject.toml [tool.ruff] line-length

# TEST SEAM ONLY. Each value makes the generation wrong in a way one self-check condition exists to
# catch, so a test can show that condition refusing. Never set it in a real release. A source fault
# is (module, old, new), with <repository>, <decided>, <new> and <old> filled in.
FAULT_ENV = "RELEASE_INERT_FAULT"
_SOURCE_FAULTS = {
    "alter_older_version": (
        "history",
        '    decided="2026-08-11",\n',
        '    decided="2026-08-12",\n',
    ),
    "widen_new_version": (
        "policy",
        "permitted_authors=frozenset({DEPENDABOT, FORK_SECURE_UPSTREAM_SYNC}),",
        'permitted_authors=frozenset({DEPENDABOT, FORK_SECURE_UPSTREAM_SYNC, "x[bot]"}),',
    ),
    "add_second_repository": (
        "policy",
        '            "<repository>",\n',
        '            "<repository>",\n            "alobarquest/unasked",\n',
    ),
    "wrong_decided": ("policy", '    decided="<decided>",\n', '    decided="1999-01-01",\n'),
    "stale_current_version": (
        "policy",
        "CURRENT_VERSION: Final = <new>\n",
        "CURRENT_VERSION: Final = <old>\n",
    ),
    "stale_current_function": (
        "policy",
        "    return V<new>\n",
        '    return V<new>.__class__(**{**V<new>.__dict__, "version": <old>})\n',
    ),
    "unregistered_version": ("history", "        V<new>,\n    )\n}", "    )\n}"),
}
_CONTRACT_FAULTS = ("corrupt_contract", "stale_contract")
FAULTS = (*_SOURCE_FAULTS, *_CONTRACT_FAULTS)

EXIT_RELEASED, EXIT_REFUSED, EXIT_ALREADY_PRESENT = 0, 1, 2

# Fields an inert-only release rewrites; every other projected field must be version N's.
RELEASE_PROSE = ("version", "decided", "rationale")
INERT_RELEASE_FIELDS = ("repositories", "rationale")

_PROBE = """
import json, sys
from pathlib import Path

import app.deploy_policy as live
import app.deploy_policy_history as history

root = Path(sys.argv[1]).resolve()
for module in (live, history):
    if not Path(module.__file__).resolve().is_relative_to(root):
        raise SystemExit(f"imported {module.__file__}, which is outside {root}")
print(json.dumps({
    "current_version": live.CURRENT_VERSION,
    "current_is": live.current().version,
    "registry": sorted(history.REGISTRY),
    "policies": {str(n): live.policy_dict(p) for n, p in history.REGISTRY.items()},
}))
"""


class Refusal(Exception):
    """The release cannot be made; the message says why."""


@dataclass(frozen=True)
class Snapshot:
    current_version: int
    current_is: int
    registry: list[int]
    policies: dict[int, dict]


def _isolated_env() -> dict[str, str]:
    # A fresh bytecode cache, so a fresh interpreter never runs a `.pyc` compiled from bytes that
    # an edit within the same second replaced.
    env = dict(os.environ)
    env["PYTHONDONTWRITEBYTECODE"] = "1"
    env["PYTHONPYCACHEPREFIX"] = tempfile.mkdtemp(prefix="release-inert-pycache-")
    return env


def _run(args: list[str]) -> str:
    done = subprocess.run(
        [sys.executable, *args], cwd=ROOT, env=_isolated_env(), capture_output=True, text=True
    )
    if done.returncode != 0:
        raise Refusal(f"{' '.join(args[:2])} failed ({done.returncode}): {done.stderr.strip()}")
    return done.stdout


def probe() -> Snapshot:
    raw = json.loads(_run(["-c", _PROBE, str(ROOT)]))
    return Snapshot(
        current_version=raw["current_version"],
        current_is=raw["current_is"],
        registry=raw["registry"],
        policies={int(n): served for n, served in raw["policies"].items()},
    )


def canonical_digest(served: dict) -> str:
    encoded = json.dumps(served, sort_keys=True, separators=(",", ":"), ensure_ascii=False)
    return hashlib.sha256(encoded.encode("utf-8")).hexdigest()


def without_release_fields(served: dict) -> dict:
    kept = json.loads(json.dumps(served))
    for key in RELEASE_PROSE:
        kept.pop(key, None)
    inert = kept.get("inert_landing")
    if isinstance(inert, dict):
        for key in INERT_RELEASE_FIELDS:
            inert.pop(key, None)
    return kept


# ---------------------------------------------------------------------------
# The self-check.
# ---------------------------------------------------------------------------


def _earlier_versions_unchanged(before: Snapshot, after: Snapshot) -> list[str]:
    """(a) Every version 1..N projects exactly what it projected before the edit."""
    failures = []
    for number in range(1, before.current_version + 1):
        old, new = before.policies.get(number), after.policies.get(number)
        if old is None or new is None or canonical_digest(old) != canonical_digest(new):
            failures.append(f"(a) version {number} no longer projects what it did")
    return failures


def _new_version_adds_only(
    before: Snapshot, after: Snapshot, repository: str, decided: str
) -> list[str]:
    """(b) Version N+1 is version N, its prose, and exactly one more inert repository."""
    n = before.current_version
    released, previous = after.policies.get(n + 1), before.policies[n]
    if released is None:
        return [f"(b) version {n + 1} is not registered"]
    failures = []
    expected = sorted({*previous["inert_landing"]["repositories"], repository})
    if released.get("decided") != decided:
        failures.append(f"(b) version {n + 1} is not decided {decided}")
    if (released.get("inert_landing") or {}).get("repositories") != expected:
        failures.append(f"(b) version {n + 1}'s inert population is not version {n}'s plus one")
    if without_release_fields(released) != without_release_fields(previous):
        failures.append(f"(b) version {n + 1} changes more than the inert population")
    return failures


def _contract_is_new_version(before: Snapshot) -> list[str]:
    """(c) The regenerated contract parses and names version N+1."""
    n = before.current_version
    try:
        contract_version = json.loads(CONTRACT.read_text(encoding="utf-8")).get("policy_version")
    except (OSError, ValueError, AttributeError) as error:
        return [f"(c) {CONTRACT.relative_to(ROOT)} does not parse: {error}"]
    if contract_version != n + 1:
        return [f"(c) the contract names version {contract_version}, not {n + 1}"]
    return []


def _new_version_in_force(before: Snapshot, after: Snapshot) -> list[str]:
    """(d) CURRENT_VERSION and current() are version N+1, and the registry gained exactly it."""
    n, failures = before.current_version, []
    if after.current_version != n + 1 or after.current_is != n + 1:
        failures.append(
            f"(d) CURRENT_VERSION is {after.current_version} and current() is version "
            f"{after.current_is}; both must be {n + 1}"
        )
    if after.registry != [*before.registry, n + 1]:
        failures.append(f"(d) the registry is {after.registry}, not {before.registry} + {n + 1}")
    return failures


def self_check(before: Snapshot, after: Snapshot, repository: str, decided: str) -> list[str]:
    """Every reason the edited tree is not version N plus `repository`. Empty means it is."""
    return [
        *_earlier_versions_unchanged(before, after),
        *_new_version_adds_only(before, after, repository, decided),
        *_contract_is_new_version(before),
        *_new_version_in_force(before, after),
    ]


# ---------------------------------------------------------------------------
# Generation: text transforms over the two modules, in the shape of the hand-made releases.
# ---------------------------------------------------------------------------


def _one(pattern: str, text: str, what: str, flags: int = 0) -> re.Match[str]:
    found = list(re.finditer(pattern, text, flags))
    if len(found) != 1:
        raise Refusal(f"expected exactly one {what}, found {len(found)}")
    return found[0]


def _replace_once(text: str, old: str, new: str, what: str) -> str:
    if text.count(old) != 1:
        raise Refusal(f"expected exactly one {what}, found {text.count(old)}")
    return text.replace(old, new)


def _literal_lines(text: str, indent: int) -> str:
    """`text` as implicitly concatenated string literals, each line within the line length."""
    width = LINE_LENGTH - indent - 2  # the two quotes
    words, pieces, line = text.split(" "), [], ""
    for word in words:
        candidate = f"{line} {word}" if line else word
        if len(candidate) + 1 <= width:  # + 1 for the trailing space every piece but the last has
            line = candidate
            continue
        if len(word) + 1 > width:
            raise Refusal(f"{word[:40]}... is too long to fit one line of the policy module")
        if line:
            pieces.append(line)
        line = word
    pieces.append(line)
    pad = " " * indent
    rendered = [f'{pad}"{piece} "' for piece in pieces[:-1]] + [f'{pad}"{pieces[-1]}"']
    return "\n".join(rendered) + "\n"


def _comment_lines(text: str, indent: int) -> str:
    prefix = " " * indent + "# "
    wrapped = textwrap.wrap(
        text, LINE_LENGTH - len(prefix), break_long_words=True, break_on_hyphens=False
    )
    return "".join(f"{prefix}{line}\n" for line in wrapped)


def _sentence(reason: str) -> str:
    return reason if reason.endswith((".", "!", "?")) else reason + "."


def _inert_rationale(n: int, count: int, repository: str, reason: str, decided: str) -> str:
    return (
        f"The rule ADR-0038 declared, over the {count} repositories version {n} named and one "
        f"more, with the same authors. "
        f"WHAT IS ADDED. {repository}, by version {n + 1}, {decided}: {_sentence(reason)} "
        f"Each fork joining the orchestrator's fork-sync lane is an explicit, versioned grant in "
        f"this policy (Devon, 2026-10-24), and this version was generated by "
        f"`scripts/release_inert_repository.py`, which adds one repository and refuses the release "
        f"unless every other term projects unchanged. "
        f"NOTHING ELSE IS WIDENED. The authors, the excluded ecosystems, the freshness condition "
        f"and the exempted authors are version {n}'s. "
        f"The deploying population and every term keyed off it are version {n}'s objects, "
        f"unchanged. The two populations remain disjoint."
    )


def _policy_rationale(n: int, repository: str, reason: str) -> str:
    return (
        f"Version {n}'s populations and terms, with one repository added to the inert lane: "
        f"{repository}. Nothing else is widened: the same deploying repositories, the same change "
        f"classes, the same risks, the same criteria, the same remedies, the same rollout pins, "
        f"the same conditions on the act, and the same inert authors and terms. "
        f"WHY IT EXISTS. {_sentence(reason)}"
    )


_RATIONALE_BLOCK = r"    rationale=\(\n(?:        .*\n)+?    \),\n"


def _release_policy_module(
    source: str, n: int, repository: str, reason: str, decided: str, inert_count: int
) -> tuple[str, str]:
    """(the new deploy_policy.py, version N's verbatim block for the history module)."""
    header = _one(
        rf"^# (-+)\n# Version {n} -- the version in force\.\n# -+\n\n",
        source,
        f"version {n} section header",
        re.M,
    )
    rule = header.group(1)
    current_line = f"CURRENT_VERSION: Final = {n}\n"
    end = source.find(current_line, header.end())
    if end < 0 or source.count(current_line) != 1:
        raise Refusal(f"expected exactly one `{current_line.strip()}`")
    block = source[header.end() : end]
    parts = _one(
        rf"\A(?P<comment>(?:#.*\n)*)"
        rf"(?P<inert>_V{n}_INERT: Final = InertLanding\(\n.*?\n\)\n)\n\n"
        rf"(?P<policy>V{n}: Final = DeployPolicy\(\n.*?\n\)\n)\n\n\Z",
        block,
        f"version {n} definitions",
        re.S,
    )
    old_decided = _one(r'    decided="(\d{4}-\d{2}-\d{2})",\n', parts["policy"], "decided date")
    moved = (
        f"# {rule}\n# Version {n} -- Devon, {old_decided.group(1)}.\n# {rule}\n\n"
        f"{parts['comment']}{parts['inert']}\n\n{parts['policy']}\n\n"
    )

    # The new inert population: version N's, every entry and comment verbatim, plus one.
    inert = parts["inert"].replace(f"_V{n}_INERT: Final", f"_V{n + 1}_INERT: Final", 1)
    closing = "        }\n    ),\n    permitted_authors="
    inert = _replace_once(
        inert,
        closing,
        _comment_lines(f"Added by version {n + 1}, {decided}. {_sentence(reason)}", 12)
        + f'            "{repository}",\n'
        + closing,
        "close of the inert repositories",
    )
    _one(_RATIONALE_BLOCK, inert, "inert rationale")
    inert = re.sub(
        _RATIONALE_BLOCK,
        lambda _: (
            "    rationale=(\n"
            + _literal_lines(_inert_rationale(n, inert_count, repository, reason, decided), 8)
            + "    ),\n"
        ),
        inert,
        count=1,
    )

    policy = parts["policy"].replace(f"V{n}: Final", f"V{n + 1}: Final", 1)
    policy = _replace_once(policy, f"    version={n},\n", f"    version={n + 1},\n", "version")
    policy = policy.replace(old_decided.group(0), f'    decided="{decided}",\n', 1)
    _one(_RATIONALE_BLOCK, policy, "policy rationale")
    policy = re.sub(
        _RATIONALE_BLOCK,
        lambda _: (
            "    rationale=(\n"
            + _literal_lines(_policy_rationale(n, repository, reason), 8)
            + "    ),\n"
        ),
        policy,
        count=1,
    )
    policy = re.sub(
        r"(# The SAME OBJECT versions? \d+)(?: (?:to|and) \d+)? declared",
        rf"\1 to {n} declared",
        policy,
        count=1,
    )
    policy = _replace_once(
        policy,
        f"    inert_landing=_V{n}_INERT,\n",
        f"    inert_landing=_V{n + 1}_INERT,\n",
        "inert_landing reference",
    )

    comment = (
        f"VERSION {n}'S INERT POPULATION AND TERMS, with one more repository. The same authors, "
        f"the same exclusions, the same freshness condition and the same exempted authors."
    )
    released = (
        f"# {rule}\n# Version {n + 1} -- the version in force.\n# {rule}\n\n"
        + _comment_lines(comment, 0)
        + f"{inert}\n\n{policy}\n\n"
    )
    out = (
        source[: header.start()]
        + released
        + f"CURRENT_VERSION: Final = {n + 1}\n"
        + source[end + len(current_line) :]
    )
    out = _replace_once(
        out,
        f"def current() -> DeployPolicy:\n    return V{n}\n",
        f"def current() -> DeployPolicy:\n    return V{n + 1}\n",
        "current()",
    )
    return out, moved


def _release_history_module(source: str, n: int, moved: str) -> str:
    out = _replace_once(
        source,
        f"    V{n},\n    DeployPolicy,\n",
        f"    V{n + 1},\n    DeployPolicy,\n",
        f"import of V{n}",
    )
    anchor = "# Every version ever, retained."
    out = _replace_once(out, anchor, moved + anchor, "registry comment")
    return _replace_once(
        out, f"        V{n},\n    )\n}}", f"        V{n},\n        V{n + 1},\n    )\n}}", "registry"
    )


def _inject(
    fault: str, n: int, repository: str, decided: str, policy: str, history: str
) -> tuple[str, str]:
    if fault not in _SOURCE_FAULTS:
        return policy, history
    module, old, new = _SOURCE_FAULTS[fault]
    fill = {"<repository>": repository, "<decided>": decided, "<new>": str(n + 1), "<old>": str(n)}
    for placeholder, value in fill.items():
        old, new = old.replace(placeholder, value), new.replace(placeholder, value)
    if module == "policy":
        return _replace_once(policy, old, new, f"fault {fault}"), history
    return policy, _replace_once(history, old, new, f"fault {fault}")


# ---------------------------------------------------------------------------
# The command.
# ---------------------------------------------------------------------------


def _validated(repository: str, reason: str) -> tuple[str, str]:
    name = repository.strip().lower()
    if not REPOSITORY_NAME.fullmatch(name):
        raise Refusal(f"{repository!r} is not an owner/name repository")
    text = " ".join(reason.split())
    if not text:
        raise Refusal("--reason is empty")
    if any(ch in text for ch in '"\\') or not text.isprintable():
        # Kept out rather than escaped: an escaped quote is a literal ruff would requote.
        raise Refusal("--reason may not contain a double quote, a backslash or a control character")
    return name, text


def _already_present(before: Snapshot, repository: str) -> bool:
    """Whether version N already admits `repository`; refuses a tree it cannot release from."""
    n = before.current_version
    if before.current_is != n or not before.registry or before.registry[-1] != n:
        raise Refusal(f"the tree is inconsistent before the release: {before.current_is}, {n}")
    previous = before.policies[n]
    inert = previous.get("inert_landing")
    if inert is None:
        raise Refusal(f"version {n} declares no inert population to add to")
    if repository in inert["repositories"]:
        return True
    if repository in previous["repositories"]:
        raise Refusal(f"{repository} is in the deploying population; the two stay disjoint")
    return False


def _write_release(
    before: Snapshot, repository: str, reason: str, decided: str, fault: str | None
) -> None:
    """Edit, regenerate, self-check; on any failure put every touched file back byte for byte."""
    n = before.current_version
    originals = {path: path.read_bytes() for path in TOUCHED}
    try:
        policy, moved = _release_policy_module(
            originals[POLICY].decode("utf-8"),
            n,
            repository,
            reason,
            decided,
            len(before.policies[n]["inert_landing"]["repositories"]),
        )
        history = _release_history_module(originals[HISTORY].decode("utf-8"), n, moved)
        if fault is not None:
            policy, history = _inject(fault, n, repository, decided, policy, history)
        POLICY.write_text(policy, encoding="utf-8")
        HISTORY.write_text(history, encoding="utf-8")
        sys.stderr.write(_run(["-m", "scripts.write_ratified_rollout_policy"]))
        if fault == "corrupt_contract":
            CONTRACT.write_text("{\n", encoding="utf-8")
        elif fault == "stale_contract":
            CONTRACT.write_bytes(originals[CONTRACT])
        failures = self_check(before, probe(), repository, decided)
        if failures:
            raise Refusal("self-check failed:\n  " + "\n  ".join(failures))
    except BaseException:
        for path, data in originals.items():
            path.write_bytes(data)
        raise


def release(repository: str, reason: str, decided: str, fault: str | None) -> int:
    if fault is not None and fault not in FAULTS:
        raise Refusal(f"{FAULT_ENV}={fault!r} is not one of {', '.join(FAULTS)}")
    before = probe()
    if _already_present(before, repository):
        print(
            f"{repository} is already in version {before.current_version}'s inert population",
            file=sys.stderr,
        )
        return EXIT_ALREADY_PRESENT
    _write_release(before, repository, reason, decided, fault)
    print(f"{before.current_version + 1} {repository}")
    return EXIT_RELEASED


class _Parser(argparse.ArgumentParser):
    # argparse exits 2 on a usage error, which is this command's "already present". Refuse instead.
    def error(self, message: str) -> NoReturn:
        raise Refusal(message)


def main(argv: list[str] | None = None) -> int:
    parser = _Parser(
        description="Release the next deploy-policy version, one more inert repository."
    )
    parser.add_argument("--repository", required=True, help="owner/name, lower-cased")
    parser.add_argument("--reason", required=True, help="one sentence: why it is admitted")
    try:
        args = parser.parse_args(argv)
        repository, reason = _validated(args.repository, args.reason)
        return release(repository, reason, date.today().isoformat(), os.environ.get(FAULT_ENV))
    except Refusal as refusal:
        print(f"release refused: {refusal}", file=sys.stderr)
        return EXIT_REFUSED
    except Exception as error:  # every file is already restored by `release`
        print(f"release failed: {type(error).__name__}: {error}", file=sys.stderr)
        return EXIT_REFUSED


if __name__ == "__main__":
    sys.exit(main())
