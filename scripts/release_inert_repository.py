def _validated(repository: str, reason: str) -> tuple[str, str]:
    name = repository.strip().lower()
    if not REPOSITORY_NAME.fullmatch(name):
        raise Refusal(f"{repository!r} is not an owner/name repository")
    text = " ".join(reason.split())
    if not text:
        raise Refusal("--reason is empty")
    if any(ch in text for ch in '"\\') or not text.isprintable():
        # Kept out rather than escaped: an escaped quote is a literal ruff would requote.
        raise Refusal("--reason may not contain a double quote, a backslash or a control character")
    return name, text


def _already_present(before: Snapshot, repository: str) -> bool:
    """Whether version N already admits `repository`; refuses a tree it cannot release from."""
    n = before.current_version
    if before.current_is != n or not before.registry or before.registry[-1] != n:
        raise Refusal(f"the tree is inconsistent before the release: {before.current_is}, {n}")
    previous = before.policies[n]
    inert = previous.get("inert_landing")
    if inert is None:
        raise Refusal(f"version {n} declares no inert population to add to")
    if repository in inert["repositories"]:
        return True
    if repository in previous["repositories"]:
        raise Refusal(f"{repository} is in the deploying population; the two stay disjoint")
    return False


def _write_release(
    before: Snapshot, repository: str, reason: str, decided: str, fault: str | None
) -> None:
    """Edit, regenerate, self-check; on any failure put every touched file back byte for byte."""
    n = before.current_version
    originals = {path: path.read_bytes() for path in TOUCHED}
    try:
        policy, moved = _release_policy_module(
            originals[POLICY].decode("utf-8"),
            n,
            repository,
            reason,
            decided,
            len(before.policies[n]["inert_landing"]["repositories"]),
            before.same_landing_since,
        )
        history = _release_history_module(originals[HISTORY].decode("utf-8"), n, moved)
        if fault is not None:
            policy, history = _inject(fault, n, repository, decided, policy, history)
        POLICY.write_text(policy, encoding="utf-8")
        HISTORY.write_text(history, encoding="utf-8")
        _sort_history_imports()
        sys.stderr.write(_run("contract writer", ["-m", "scripts.write_ratified_rollout_policy"]))
        if fault == "corrupt_contract":
            CONTRACT.write_text("{\n", encoding="utf-8")
        elif fault == "stale_contract":
            CONTRACT.write_bytes(originals[CONTRACT])
        elif fault == "reformat_contract":
            regenerated = json.loads(CONTRACT.read_text(encoding="utf-8"))
            CONTRACT.write_text(json.dumps(regenerated, indent=4), encoding="utf-8")
        failures = self_check(before, probe(), repository, decided)
        if failures:
            raise Refusal("self-check failed:\n  " + "\n  ".join(failures))
    except BaseException:
        for path, data in originals.items():
            path.write_bytes(data)
        raise


def _sort_history_imports() -> None:
    """Put the history module's imports in ruff's order (rule I001), and nothing else.

    A missing ruff is left to the self-check's condition (e), which refuses the release.
    """
    ruff = Path(sys.executable).parent / "ruff"
    if ruff.exists():
        subprocess.run(
            [str(ruff), "check", "--fix", "--quiet", "--select", "I", str(HISTORY)],
            cwd=ROOT,
            capture_output=True,
            text=True,
        )


def _report(status: str, version: int, repository: str) -> None:
    """The one line this command writes to stdout."""
    print(json.dumps({"status": status, "version": version, "repository": repository}))


def release(repository: str, reason: str, decided: str, fault: str | None) -> int:
    if fault is not None and fault not in FAULTS:
        raise Refusal(f"{FAULT_ENV}={fault!r} is not one of {', '.join(FAULTS)}")
    before = probe()
    if _already_present(before, repository):
        _report("already_present", before.current_version, repository)
        return EXIT_DONE
    _write_release(before, repository, reason, decided, fault)
    _report("released", before.current_version + 1, repository)
    return EXIT_DONE


class _Parser(argparse.ArgumentParser):
    # argparse exits 2 on a usage error; this script's own refusals are 1, so refuse instead.
    def error(self, message: str) -> NoReturn:
        raise Refusal(message)

    # Help and usage go to stderr: stdout carries only the one JSON line.
    def print_help(self, file=None) -> None:
        super().print_help(sys.stderr)

    # And `--help` exits 0, which means "done" here; no release was made, so refuse.
    def exit(self, status: int = 0, message: str | None = None) -> NoReturn:
        raise Refusal(message or "no release made")


def main(argv: list[str] | None = None) -> int:
    parser = _Parser(
        description="Release the next deploy-policy version, one more inert repository."
    )
    parser.add_argument("--repository", required=True, help="owner/name, lower-cased")
    parser.add_argument("--reason", required=True, help="one sentence: why it is admitted")
    try:
        args = parser.parse_args(argv)
        repository, reason = _validated(args.repository, args.reason)
        return release(repository, reason, date.today().isoformat(), os.environ.get(FAULT_ENV))
    except Refusal as refusal:
        print(f"release refused: {refusal}", file=sys.stderr)
        return EXIT_REFUSED
    except Exception as error:  # every file is already restored by `release`
        print(f"release failed: {type(error).__name__}: {error}", file=sys.stderr)
        return EXIT_REFUSED


if __name__ == "__main__":
    sys.exit(main())
